PAGES = [("index.html", "Overview"), ("models.html", "Models"), ("extend.html", "Build your own")]


def page(fname, title, kicker, h1, lead, meta, sections, body, desc):
    toc = "".join(f'<a href="#s{i}"><span>{i:02d}</span>{html.escape(t)}</a>' for i, t in enumerate(sections, 1))
    others = "".join(f'<a class="{"cur" if f == fname else ""}" href="{f}">{html.escape(t)}</a>' for f, t in PAGES)
    crumbs = '<a href="index.html">AI Agent Guide</a>' + ("" if fname == "index.html" else f"<span>/</span>{html.escape(title)}")
    body = re.sub(r"(<table.*?</table>)", r'<div class="tw">\1</div>', body, flags=re.S)
    out = HEAD.format(desc=html.escape(desc, quote=True), title=html.escape(title), url=SITE + "ai-agent-guide/" + ("" if fname == "index.html" else fname),
                      css=BASE_CSS + EXTRA_CSS, crumbs=crumbs, kicker=kicker, h1=h1, lead=lead, meta=meta, toc=toc, body=body, others=others)
    (OUT / fname).write_text(out)


def h2(n, t):
    return f'<h2 id="s{n}"><span class="stepno">{n:02d}</span>{t}</h2>'


def load_models(repo):
    d = repo / "skills/model-dictionary"
    idx = yaml.safe_load((d / "index.yaml").read_text())["entries"]
    rows = []
    for e in idx:
        ent = yaml.safe_load((d / "entries" / f"{e['id']}.yaml").read_text())
        c = ent["citation"]
        rows.append(dict(id=e["id"], authors=c.get("authors", ""), year=c.get("year", ""), cls=e.get("model_class", ""),
                         status=e.get("verified_status", ""), title=c.get("title", "")))
    return rows


